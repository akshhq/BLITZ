#!/usr/bin/env node

'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'data.js'), 'utf8'), ctx);
const D = ctx.window.BLITZ_DATA || {};

const q = (v) => (v === undefined || v === null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (Array.isArray(a) && a.length ? `array[${a.map((x) => q(x)).join(', ')}]::text[]` : `'{}'::text[]`);
const js = (v) => `'${JSON.stringify(Array.isArray(v) ? v : []).replace(/'/g, "''")}'::jsonb`;
const uuid = (s) => { const h = crypto.createHash('md5').update(s).digest('hex'); return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`; };
const out = ['-- Generated by tools/generate-seed.js from data.js. Run AFTER schema.sql.', 'begin;', ''];

out.push('-- announcements');
(D.announcements || []).forEach((a) => out.push(
  `insert into public.announcements (id, title, date, summary, body, link) values (${q(a.id)}, ${q(a.title)}, ${q(a.date)}, ${q(a.summary || '').replace(/^NULL$/, "''")}, ${q(a.body || '').replace(/^NULL$/, "''")}, ${q(a.link)}) on conflict (id) do nothing;`));

out.push('', '-- events');
(D.events || []).forEach((e) => {
  const speakers = Array.isArray(e.speakers) ? e.speakers : (e.speaker ? [e.speaker] : []);
  out.push(
    `insert into public.events (id, title, date, time, location, description, category, layout, format, platform, participants, speakers, key_points, winners, sessions, competition_sections, links, image, image_alt, logo, brochure, additional_info, placeholder) values (` +
    [q(e.id), q(e.title), q(e.date), q(e.time), q(e.location), `'${String(e.description || '').replace(/'/g, "''")}'`, q(e.category), q(e.layout || 'event'), q(e.format), q(e.platform), q(e.participants),
      arr(speakers), arr(e.keyPoints), js(e.winners), js(e.sessions), js(e.competitionSections), js(e.links), q(e.image), q(e.imageAlt), q(e.logo), q(e.brochure), q(e.additionalInfo), e.placeholder === true ? 'true' : 'false'].join(', ') +
    `) on conflict (id) do nothing;`);
});

out.push('', '-- event images (the one source of images: an event\'s own image is its first image; the Gallery star starts off)');
(D.events || []).filter((e) => e.image && /^(assets\/|storage:)[A-Za-z0-9\/_.-]{1,200}$/.test(e.image) && !/\.\./.test(e.image)).forEach((e) => out.push(
  `insert into public.event_images (id, event_id, image, alt, sort_order) values ('${uuid('event-image:' + e.id + ':0')}', ${q(e.id)}, ${q(e.image)}, ${`'${String(e.imageAlt || '').replace(/'/g, "''")}'`}, 10) on conflict (id) do nothing;`));

out.push('', '-- team (sort_order in steps of 10 so the admin can slot people in between)');
(D.team || []).forEach((m, i) => out.push(
  `insert into public.team_members (id, name, position, tier, photo, sort_order) values ('${uuid('team:' + m.name)}', ${q(m.name)}, ${q(m.position)}, ${q(m.tier)}, ${q(m.photo)}, ${(i + 1) * 10}) on conflict (id) do nothing;`));

out.push('', '-- gallery');
(D.gallery || []).forEach((g, i) => out.push(
  `insert into public.gallery_items (id, title, description, image, alt, media_type, date_label, location, sort_order) values ('${uuid('gallery:' + (g.id || g.title))}', ${q(g.title)}, ${q(g.description)}, ${q(g.image)}, ${q(g.alt)}, ${q(g.mediaType === 'illustration' ? 'illustration' : 'photo')}, ${q(g.date)}, ${q(g.location)}, ${(i + 1) * 10}) on conflict (id) do nothing;`));

out.push('', '-- collaborations');
(D.collaborations || []).forEach((c, i) => out.push(
  `insert into public.collaborations (id, name, type, logo, url, sort_order) values ('${uuid('collab:' + c.name)}', ${q(c.name)}, ${q(c.type)}, ${q(c.logo)}, ${q(c.url)}, ${(i + 1) * 10}) on conflict (id) do nothing;`));

out.push('', 'commit;', '');
fs.writeFileSync(path.join(root, 'supabase', 'seed.sql'), out.join('\n'));
console.log(`supabase/seed.sql written: ${(D.announcements || []).length} announcements, ${(D.events || []).length} events, ${(D.team || []).length} team, ${(D.gallery || []).length} gallery, ${(D.collaborations || []).length} collaborations`);
